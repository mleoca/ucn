/**
 * eval/check-matrix-cases.js - one change each, and whether it breaks code
 * the change did not touch.
 *
 * Each case is a tiny project (`base`, committed) and a change (`after`:
 * path -> new content, or null to delete the file). `expect` is what the
 * language's own toolchain says once the change is applied: 'break' or
 * 'clean'. `answer` is the pre-commit check's TRUST for the change and
 * `detail` its verdict per changed symbol, the same for the worktree and
 * for the staged tree.
 *
 * Two consumers share this data:
 *   - eval/run-check-matrix.js judges every case with its compiler and
 *     fails on READY for a change the compiler rejects (false-ready), on
 *     BLOCKED for a change it accepts (a break that was not one), and on a
 *     staged answer that differs from the worktree's;
 *   - test/check-change-kinds.test.js pins the check's answer on every
 *     case, with no toolchain needed.
 *
 * The cases are chosen where a line-oriented check goes wrong: a body edit
 * that is inert next to one that changes what the body's callers receive,
 * an addition that existing code must now answer to, a removal that
 * nothing names by call.
 */

